export type TranslationKey = keyof (typeof translations)['ro'];

export function translate(lang: Language, key: TranslationKey): string {
  return translations[lang][key] ?? translations.ro[key] ?? key;
}

// Interpolare simplă: „Am găsit {n} destinații" + { n: 3 } → „Am găsit 3 destinații"
export function tf(
  lang: Language,
  key: TranslationKey,
  vars: Record<string, string | number>,
): string {
  let text = translate(lang, key);
  for (const [k, v] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return text;
}

export function localeOf(lang: Language): string {
  return lang === 'en' ? 'en-US' : lang === 'ru' ? 'ru-RU' : 'ro-RO';
}
